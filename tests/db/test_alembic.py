"""
tests.db.test_alembic

Модуль тестов для проверки работы Alembic — инструмента миграций баз данных
в проекте DocAgent‑mini.

Содержит тесты, проверяющие корректность взаимодействия Alembic с базой данных,
в том числе:
- успешное установление соединения с БД;
- возможность выполнения базовых команд Alembic
    (например, получения текущей версии схемы БД).

Цель модуля — убедиться, что механизм миграций работает стабильно,
а Alembic корректно взаимодействует с хранилищем данных,
что критично для поддержания целостности схемы БД при развитии приложения.
"""

import pytest
from alembic import command


def test_alembic_connection(alembic_config):
    """
    Тест проверяет успешное подключение Alembic к базе данных.
    Выполняет команду 'current' для получения текущей версии схемы БД.

    Args:
        alembic_config: объект конфигурации Alembic,
        используемый для выполнения команд.

    Raises:
        pytest.Failed: если Alembic не смог выполнить команду 'current',
                      с описанием возникшей ошибки.
    """
    try:
        command.current(alembic_config)
    except Exception as e:
        pytest.fail(f"Alembic не смог выполнить команду 'current': {e}")
